#!/usr/bin/env python3
"""Generate src/entities_data.h from the WHATWG named character reference table.

Usage:
    python3 tools/gen_entities.py [tools/entities.json] > src/entities_data.h

The input is https://html.spec.whatwg.org/entities.json (a copy is kept in
tools/entities.json so the build never needs network access). The output is a
bytewise-sorted C array suitable for binary search.
"""

import json
import sys


def main() -> int:
    path = sys.argv[1] if len(sys.argv) > 1 else "tools/entities.json"
    with open(path, encoding="utf-8") as fh:
        table = json.load(fh)

    rows = []
    for key, value in table.items():
        name = key[1:]  # strip leading '&'
        cps = value["codepoints"]
        if len(cps) > 2:
            raise SystemExit(f"entity {key} has more than two code points")
        cp1 = cps[0]
        cp2 = cps[1] if len(cps) > 1 else 0
        rows.append((name.encode("ascii"), cp1, cp2))

    rows.sort(key=lambda r: r[0])
    max_len = max(len(r[0]) for r in rows)
    legacy_max = max(len(r[0]) for r in rows if not r[0].endswith(b";"))

    out = sys.stdout
    out.write("/* Generated by tools/gen_entities.py from the WHATWG entities.json.\n")
    out.write(" * DO NOT EDIT BY HAND. */\n\n")
    out.write("#ifndef H2M_ENTITIES_DATA_H\n#define H2M_ENTITIES_DATA_H\n\n")
    out.write(f"#define H2M_ENTITY_COUNT {len(rows)}\n")
    out.write(f"#define H2M_ENTITY_MAX_NAME {max_len}\n")
    out.write(f"#define H2M_ENTITY_LEGACY_MAX_NAME {legacy_max}\n\n")
    out.write("static const struct h2m_entity_row {\n")
    out.write("    const char *name;\n    unsigned char len;\n")
    out.write("    unsigned int cp1;\n    unsigned int cp2;\n")
    out.write("} h2m_entity_table[H2M_ENTITY_COUNT] = {\n")
    for name, cp1, cp2 in rows:
        s = name.decode("ascii")
        out.write(f'    {{"{s}", {len(name)}, 0x{cp1:X}, 0x{cp2:X}}},\n')
    out.write("};\n\n#endif /* H2M_ENTITIES_DATA_H */\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
